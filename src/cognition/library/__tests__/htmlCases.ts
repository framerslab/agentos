/**
 * The HTML reader's cases. The Node test reads each one through a stand-in of plain objects and the browser test
 * through the page's own DOMParser in Chromium and in WebKit, so one answer holds over both.
 */

/** A page, the options it is read with, and what the reader answers for it. */
export interface HtmlCase {
  readonly name: string;
  readonly html: string;
  readonly options?: { readonly maxCharacters?: number; readonly maxTableRows?: number; readonly maxTableColumns?: number };
  readonly title: string | null;
  readonly markdown: string;
  readonly images: number;
  readonly cut: boolean;
}

/** Lines joined with line feeds. */
const lines = (...each: string[]): string => each.join('\n');

